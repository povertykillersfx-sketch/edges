export function getBuiltinTemplate(id) {
  return BUILTIN_TEMPLATES.find((t) => t.id === id) || null;
}

export function mergeTemplateRow(row) {
  const builtin = getBuiltinTemplate(row?.id) || {};
  return {
    ...builtin,
    ...row,
    schema: row?.schema || builtin.schema || { fields: [] },
    default_config: row?.default_config || builtin.default_config || {},
  };
}
